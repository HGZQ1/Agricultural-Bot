"""Optional Nav2 command smoothing before the existing safety stop chain.

This helper does not launch or activate nodes.  The caller must conditionally
launch ``nav2_velocity_smoother/velocity_smoother`` using the remappings below
and manage it in the same navigation lifecycle as Collision Monitor.

Jazzy 1.3.13 advances the OPEN_LOOP ramp with a WALL timer.  With simulation
time, these parameters are wall-time slopes; the observed SIM slope grows as
RTF falls.  The conservative profile is a candidate for measured evaluation,
not a replacement for the existing wheel/alignment, collision, or lock gates.
"""

from copy import deepcopy
from math import isfinite


RAW_COMMAND_TOPIC = '/cmd_vel_nav_raw'
SMOOTH_COMMAND_TOPIC = '/cmd_vel_nav_smoothed'
VELOCITY_SMOOTHER_REMAPPINGS = (
    ('cmd_vel', RAW_COMMAND_TOPIC),
    ('cmd_vel_smoothed', SMOOTH_COMMAND_TOPIC),
)


def configure_velocity_smoothing(
        parameters, enabled=False, *, smoothing_frequency=50.0,
        linear_acceleration=.01, angular_acceleration=.02,
        linear_velocity=.15, angular_velocity=.20, velocity_timeout=.25,
        lateral_velocity=0., lateral_acceleration=.01):
    """Return a copied parameter tree for the optional upstream smoother.

    Controller and behavior outputs retain their existing raw topic.  Only
    Collision Monitor's input changes; its output, stop polygon, sources and
    all footprint/alignment/keepout settings are preserved.  Emergency zeros
    generated by Collision Monitor and the base gate remain downstream of
    this component and therefore never pass through its deceleration ramp.

    Existing native ``velocity_smoother.ros__parameters`` in an opt-in YAML
    may override the numeric defaults.  Its stamped OPEN_LOOP safety routing
    is validated rather than silently replaced.  The old profile still has
    zero lateral velocity/acceleration when no override is supplied.
    """
    if not isinstance(enabled, bool):
        raise ValueError('velocity smoothing enabled must be a boolean')
    result = deepcopy(parameters)
    if not enabled:
        return result
    values = (smoothing_frequency, linear_acceleration, angular_acceleration,
              linear_velocity, angular_velocity, velocity_timeout,
              lateral_acceleration)
    if not all(isfinite(value) and value > 0. for value in values):
        raise ValueError('velocity smoothing limits must be finite and positive')
    if smoothing_frequency > 1000.:
        raise ValueError('velocity smoothing frequency must not exceed 1000 Hz')
    if not isfinite(lateral_velocity) or lateral_velocity < 0.:
        raise ValueError('lateral velocity must be finite and nonnegative')
    for name in ('controller_server', 'behavior_server', 'collision_monitor'):
        settings = result.get(name, {}).get('ros__parameters', {})
        if settings.get('enable_stamped_cmd_vel') is not True:
            raise ValueError(f'{name} must use stamped velocity commands')
    monitor = result['collision_monitor']['ros__parameters']
    if monitor.get('cmd_vel_in_topic') not in (RAW_COMMAND_TOPIC, SMOOTH_COMMAND_TOPIC):
        raise ValueError('collision monitor input must belong to the Nav2 command chain')
    if monitor.get('cmd_vel_out_topic') in (RAW_COMMAND_TOPIC, SMOOTH_COMMAND_TOPIC):
        raise ValueError('collision monitor output must remain downstream of smoothing')
    monitor['cmd_vel_in_topic'] = SMOOTH_COMMAND_TOPIC
    profile = {
        'use_sim_time': monitor.get('use_sim_time', True),
        'enable_stamped_cmd_vel': True,
        'smoothing_frequency': float(smoothing_frequency),
        'feedback': 'OPEN_LOOP',
        'scale_velocities': True,
        # Preserve upstream stamps for downstream freshness checks.
        'stamp_smoothed_velocity_with_smoothing_time': False,
        'max_velocity': [float(linear_velocity), float(lateral_velocity),
                         float(angular_velocity)],
        'min_velocity': [-float(linear_velocity), -float(lateral_velocity),
                         -float(angular_velocity)],
        'max_accel': [float(linear_acceleration),
                      float(lateral_acceleration) if lateral_velocity else 0.,
                      float(angular_acceleration)],
        'max_decel': [-float(linear_acceleration),
                      -float(lateral_acceleration) if lateral_velocity else 0.,
                      -float(angular_acceleration)],
        'deadband_velocity': [0., 0., 0.],
        'odom_topic': '/odom',
        'odom_duration': .1,
        'velocity_timeout': float(velocity_timeout),
    }
    overrides = result.get('velocity_smoother', {}).get('ros__parameters', {})
    if not isinstance(overrides, dict) or set(overrides) - set(profile):
        raise ValueError('velocity smoother profile contains unsupported parameters')
    profile.update(overrides)
    _validate_smoothing_profile(profile)
    result['velocity_smoother'] = {'ros__parameters': profile}
    return result


def _validate_smoothing_profile(profile):
    """Reject profiles that erase lateral motion or weaken stamp semantics."""
    if (profile['enable_stamped_cmd_vel'] is not True or
            profile['feedback'] != 'OPEN_LOOP' or
            profile['scale_velocities'] is not True or
            profile['stamp_smoothed_velocity_with_smoothing_time'] is not False):
        raise ValueError('smoother must retain stamped OPEN_LOOP input timing')
    for name in ('smoothing_frequency', 'velocity_timeout', 'odom_duration'):
        value = profile[name]
        if isinstance(value, bool) or not isinstance(value, (int, float)) or (
                not isfinite(value) or value <= 0.):
            raise ValueError(f'{name} must be finite and positive')
    if profile['smoothing_frequency'] > 1000.:
        raise ValueError('velocity smoothing frequency must not exceed 1000 Hz')
    for name in ('max_velocity', 'min_velocity', 'max_accel', 'max_decel',
                 'deadband_velocity'):
        values = profile[name]
        if not isinstance(values, (list, tuple)) or len(values) != 3 or not all(
                isinstance(v, (int, float)) and not isinstance(v, bool) and isfinite(v)
                for v in values):
            raise ValueError(f'{name} must have three finite numeric values')
    for axis in range(3):
        upper, lower = profile['max_velocity'][axis], profile['min_velocity'][axis]
        acceleration, deceleration = profile['max_accel'][axis], profile['max_decel'][axis]
        deadband = profile['deadband_velocity'][axis]
        if upper == lower == 0.:
            if acceleration != 0. or deceleration != 0. or deadband != 0.:
                raise ValueError('disabled smoother axes must have zero limits')
        elif not (lower < 0. < upper and acceleration > 0. and deceleration < 0. and
                  0. <= deadband < min(-lower, upper)):
            raise ValueError('active smoother axes need reverse, acceleration and braking')


def with_smoothing_lifecycle(node_names, enabled=False):
    """Add the optional smoother immediately before Collision Monitor.

    This matches installed Nav2's managed-node order.  Mission clients must
    wait for the complete navigation lifecycle before sending any goal; the
    base gate stays locked during startup and shutdown transitions.
    """
    if not isinstance(enabled, bool):
        raise ValueError('velocity smoothing enabled must be a boolean')
    result = list(node_names)
    if not enabled:
        return result
    if 'collision_monitor' not in result:
        raise ValueError('velocity smoother requires managed collision monitor')
    if 'velocity_smoother' not in result:
        result.insert(result.index('collision_monitor'), 'velocity_smoother')
    return result
